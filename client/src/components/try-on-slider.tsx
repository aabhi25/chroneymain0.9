import { useState } from "react";
import { MoveHorizontal } from "lucide-react";
import beforeImage from "@assets/stock_images/tryon_before_white_tee.jpg";
import afterImage from "@assets/stock_images/tryon_after_black_hoodie.jpg";

// Stock photos: Monstera Production on Pexels (same model, same shoot).
export default function TryOnSlider({ className = "" }: { className?: string }) {
  const [position, setPosition] = useState(50);

  return (
    <figure className={`relative w-full max-w-[400px] ${className}`}>
      <div className="relative aspect-[2/3] rounded-3xl overflow-hidden shadow-2xl border border-gray-100 select-none bg-gray-100">
        <img src={afterImage} alt="The same shopper wearing the black hoodie, generated by AI Try-On" className="absolute inset-0 w-full h-full object-cover" draggable={false} />
        <img
          src={beforeImage}
          alt="Shopper's own photo in a white T-shirt"
          className="absolute inset-0 w-full h-full object-cover"
          style={{ clipPath: `inset(0 ${100 - position}% 0 0)` }}
          draggable={false}
        />

        <span className="absolute top-4 left-4 px-3 py-1 rounded-full bg-white/90 text-xs font-semibold text-gray-700 shadow-sm">Your photo</span>
        <span className="absolute top-4 right-4 px-3 py-1 rounded-full bg-gradient-to-r from-[#FF4D4D] to-[#9333EA] text-xs font-semibold text-white shadow-sm">Wearing: Black Hoodie</span>

        <div className="absolute top-0 bottom-0 w-0.5 bg-white shadow-[0_0_8px_rgba(0,0,0,0.3)] pointer-events-none" style={{ left: `${position}%` }}>
          <div className="absolute top-1/2 left-1/2 -translate-x-1/2 -translate-y-1/2 w-11 h-11 rounded-full bg-white shadow-lg flex items-center justify-center">
            <MoveHorizontal className="w-5 h-5 text-[#9333EA]" />
          </div>
        </div>

        <input
          type="range"
          min={0}
          max={100}
          value={position}
          onChange={e => setPosition(Number(e.target.value))}
          aria-label="Drag to compare the shopper's photo with the try-on result"
          className="absolute inset-0 w-full h-full opacity-0 cursor-ew-resize"
        />
      </div>
      <figcaption className="mt-3 text-center text-xs text-gray-400">Drag to compare · Illustrative example</figcaption>
    </figure>
  );
}
